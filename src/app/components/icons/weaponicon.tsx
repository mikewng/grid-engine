const ICONS: Record<WeaponType | "none", Pixels> = {
    [WeaponType.SWORD]: SWORD,
    [WeaponType.AXE]: AXE,
    [WeaponType.SPEAR]: SPEAR,
    [WeaponType.BOW]: BOW,
    [WeaponType.STAFF]: STAFF,
    [WeaponType.BMAGIC]: TOME,
    [WeaponType.WMAGIC]: TOME,
    none: SHIELD,
};

const BASE: Palette = {
    k: COLORS.ink,
    w: COLORS.white,
    g: COLORS.steel,
    G: COLORS.steelDark,
    y: COLORS.gold,
    Y: "#b8913f",
    b: COLORS.leather,
    n: COLORS.wood,
    N: "#5e3a1a",
    o: COLORS.orb,
    P: COLORS.pages,
};

const paletteOf = (type: WeaponType | undefined): Palette => (type === WeaponType.WMAGIC
    ? { ...BASE, T: COLORS.tomeLight, D: "#c9b77a" }
    : { ...BASE, T: COLORS.tomeAnima, D: "#7e2a1c" });

/** A small pixel icon for each weapon type. */
const WeaponIcon = ({ type, className }: WeaponIconProps) => (
    <svg className={className} viewBox="0 0 16 16" shapeRendering="crispEdges" aria-hidden="true">
        {paths(outline(ICONS[type ?? "none"]), paletteOf(type)).map(({ color, d }) => <path key={color} fill={color} d={d} />)}
    </svg>
);

export default WeaponIcon;
